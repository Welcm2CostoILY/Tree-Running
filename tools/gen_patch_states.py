#!/usr/bin/env python3
"""
Generates src/main/java/com/treerunning/data/PatchStateTable.java from RuneLite's
Time Tracking plugin (PatchImplementation.java and Produce.java, BSD 2-Clause,
Copyright (c) Adam <Adam@sigterm.info> and contributors).

For every varbit value of the patch kinds Tree Running uses, it records:
  the condition (empty, growing, check-health, grown, stump, diseased, dead),
  the growth stage, the number of stages, the crop's name and its minutes per stage.

The condition comes from the object's actions in RuneLite's comments, e.g.
"Yew[Check-health,...]" is CHECK_HEALTH and "Yew tree stump[Clear,...]" is STUMP.

Usage: gen_patch_states.py <PatchImplementation.java> <Produce.java> <out.java>
"""
import re
import sys

KINDS = ["TREE", "FRUIT_TREE", "HARDWOOD_TREE", "REDWOOD", "CALQUAT", "CELASTRUS",
         "CRYSTAL_TREE", "HESPORI", "HERB", "ALLOTMENT"]

impl_src = open(sys.argv[1]).read()
produce_src = open(sys.argv[2]).read()

# ---- Produce: name, tickrate, stages, regrow, harvestStages
produce = {}
for m in re.finditer(r'^\t([A-Z_0-9]+)\("([^"]+)",\s*(.*?)\),?\s*(?://.*)?$', produce_src, re.M):
    key, name, rest = m.group(1), m.group(2), m.group(3)
    args = [a.strip() for a in rest.split(",")]
    nums = [a for a in args if re.fullmatch(r'-?\d+', a)]
    # Forms: (name, impl, item, tick, stages[, regrow, harvestStages]) / (name, contract, impl, item, tick, stages) / (name, item, tick, stages)
    if args and re.fullmatch(r'-?\d+', args[0]):
        nums = nums[1:]  # contract varbit value
    tick, stages = int(nums[0]), int(nums[1])
    produce[key] = (name, tick, stages)

def block_of(kind):
    m = re.search(r'^\t' + kind + r'\(.*?\n\t\t\{(.*?)\n\t\t\},?\s*$', impl_src, re.M | re.S)
    if not m:
        raise SystemExit("no block for " + kind)
    return m.group(1)

cond_re = re.compile(
    r'if \(value (?:>= (\d+) && value <= (\d+)|== (\d+))\)\s*\{\s*//\s*(.*?)\n\s*return new PatchState\(Produce\.([A-Z_0-9]+), CropState\.([A-Z]+), (.*?)\);',
    re.S)

def eval_stage(expr, value):
    e = re.sub(r'Produce\.([A-Z_0-9]+)\.getStages\(\)', lambda m: str(produce[m.group(1)][2]), expr)
    e = e.replace("value", str(value))
    return int(eval(e))

CODES = {"UNKNOWN": 0, "EMPTY": 1, "GROWING": 2, "CHECK_HEALTH": 3, "GROWN": 4, "STUMP": 5, "DISEASED": 6, "DEAD": 7}

def condition(produce_key, crop_state, comment):
    obj = comment.split("[")[0].lower()
    actions = comment.split("[")[1].split("]")[0] if "[" in comment else ""
    if produce_key == "WEEDS" or crop_state == "EMPTY":
        return "EMPTY"
    if crop_state == "DISEASED":
        return "DISEASED"
    if crop_state == "DEAD":
        return "DEAD"
    if "Check-health" in actions:
        return "CHECK_HEALTH"
    if "stump" in obj:
        return "STUMP"
    if crop_state == "HARVESTABLE":
        return "GROWN"
    return "GROWING"

names = []
def name_index(n):
    if n not in names:
        names.append(n)
    return names.index(n)

tables = {}
for kind in KINDS:
    body = block_of(kind)
    table = [0] * 256
    for m in cond_re.finditer(body):
        lo = int(m.group(1) or m.group(3)); hi = int(m.group(2) or m.group(3))
        comment, pkey, cstate, expr = m.group(4), m.group(5), m.group(6), m.group(7)
        cond = condition(pkey, cstate, comment)
        pname, tick, stages = produce[pkey]
        for v in range(lo, min(hi, 255) + 1):
            stage = max(0, min(eval_stage(expr, v), 31))
            ni = name_index(pname)
            # bits: condition 0-3, stage 4-8, stages 9-13, tick (minutes) 14-23, name index 24-31
            table[v] = CODES[cond] | (stage << 4) | (min(stages, 31) << 9) | (min(tick, 1023) << 14) | (ni << 24)
    tables[kind] = table

out = []
out.append("package com.treerunning.data;")
out.append("")
out.append("/**")
out.append(" * Generated by tools/gen_patch_states.py from RuneLite's Time Tracking plugin")
out.append(" * (PatchImplementation and Produce, BSD 2-Clause, Copyright (c) Adam and contributors).")
out.append(" * Do not edit by hand. Each int packs: condition (bits 0-3), stage (4-8), stages (9-13),")
out.append(" * minutes per stage (14-23) and crop name index (24-31).")
out.append(" */")
out.append("final class PatchStateTable")
out.append("{")
out.append("\tstatic final String[] NAMES = {" + ", ".join('"' + n + '"' for n in names) + "};")
out.append("")
for kind in KINDS:
    out.append("\tstatic final int[] " + kind + " = {")
    t = tables[kind]
    for i in range(0, 256, 8):
        out.append("\t\t" + ", ".join(str(x) for x in t[i:i + 8]) + ",")
    out.append("\t};")
    out.append("")
out.append("\tprivate PatchStateTable()")
out.append("\t{")
out.append("\t}")
out.append("}")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[3], "with", len(names), "crop names")
